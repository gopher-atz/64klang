#include "../PlatformInterfaces.h"
#include <cstring>

namespace K64Platform {

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
// Stub codec — returns silence (no GSM conversion on non-Windows)
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

class StubCodec : public ICodec
{
public:
    int convertGSMtoPCM(
        uint32_t sampleRate,
        const uint8_t* srcBuffer, uint32_t srcBufferSize,
        uint8_t*& dstBuffer, uint32_t& dstBufferSize) override
    {
        dstBuffer = nullptr;
        dstBufferSize = 0;
        return -1;
    }

    int convertPCMtoGSM(
        uint32_t sampleRate,
        const uint8_t* srcBuffer, uint32_t srcBufferSize,
        uint8_t*& dstBuffer, uint32_t& dstBufferSize) override
    {
        dstBuffer = nullptr;
        dstBufferSize = 0;
        return -1;
    }
};

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
// Stub GM.DLS loader — no samples available
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

class StubGMDLSLoader : public IGMDLSLoader
{
public:
    bool load() override
    {
        return false;
    }
};

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
// Stub TTS — returns silence
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

class StubTTSEngine : public ITTSEngine
{
public:
    uint8_t* synthesize(
        const std::string& text,
        uint32_t sampleRate,
        uint32_t& outSize) override
    {
        outSize = 0;
        return nullptr;
    }
};

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
// Factory functions
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

ICodec* createCodec()
{
    return new StubCodec();
}

IGMDLSLoader* createGMDLSLoader()
{
    return new StubGMDLSLoader();
}

ITTSEngine* createTTSEngine()
{
    return new StubTTSEngine();
}

} // namespace K64Platform
